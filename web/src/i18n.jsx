const Ctx = createContext(null);

function detect() {
  try {
    const saved = localStorage.getItem('wb.lang');
    if (saved === 'zh' || saved === 'en') return saved;
  } catch { /* 隐私模式 */ }
  const nav = (typeof navigator !== 'undefined' && navigator.language) || 'zh';
  return nav.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(detect);

  useEffect(() => {
    try { localStorage.setItem('wb.lang', lang); } catch { /* ignore */ }
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
  }, [lang]);

  const t = useCallback((key, vars) => {
    const row = D[key];
    let s = row ? row[lang === 'en' ? 1 : 0] : key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{{${k}}}`, String(v));
    return s;
  }, [lang]);

  const value = useMemo(() => ({ lang, setLang, t, toggle: () => setLang((l) => (l === 'zh' ? 'en' : 'zh')) }), [lang, t]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const v = useContext(Ctx);
  if (!v) throw new Error('useI18n 必须在 I18nProvider 内使用');
  return v;
}
