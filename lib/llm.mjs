/**
 * LLM 层：把一句自然语言换成图上的语义化 ops。
 *
 * 走 OpenAI 兼容协议（DeepSeek / 任何兼容端点）。
 * 关键设计：节点 schema 由前端随请求带上来（唯一真相仍在 web/src/graph/model.js），
 * 服务端只负责拼提示词、调模型、把 ops 交给 patch 校验后落盘。
 */

const SYSTEM = `You edit a node-graph workflow used by a video-generation workbench (MiniMax-H3).
You must answer with STRICT JSON only, no markdown, no prose outside JSON.

Reply shape:
{"reply": "<one short sentence in Simplified Chinese describing what you changed>", "ops": [ ...ops ]}

Full example of a valid json answer (copy this structure exactly; ops may be longer or empty):
{"reply":"补上等待完成与成品出口","ops":[{"op":"add_node","node":{"id":"n_watch1","type":"task.watch","position":{"x":620,"y":0},"data":{}}},{"op":"connect","source":"n_gen1","sourceHandle":"task_id","target":"n_watch1","targetHandle":"task_id"}]}

Allowed ops:
1) {"op":"add_node","node":{"id":"n_<short_ascii>","type":"<type>","position":{"x":0,"y":0},"data":{...}}}
2) {"op":"update_node","id":"<existing node id>","data":{...fields to merge...}}
3) {"op":"remove_node","id":"<existing node id>"}
4) {"op":"connect","source":"<id>","sourceHandle":"<handle>","target":"<id>","targetHandle":"<handle>"}
5) {"op":"disconnect","edgeId":"<existing edge id>"}

Hard rules (violating them makes the graph invalid or costs the user money):
- The result MUST be runnable end-to-end, not a fragment. A gen.* node on its own is useless:
  * every gen.* task_id output MUST connect to a task.watch node;
  * task.watch is the ONLY node that emits video_url, so it must then feed at least one output node;
  * give the graph BOTH output.preview (viewing) and output.download (saving), unless the user says otherwise.
- Canonical video chain: text.prompt (+ text.negative) -> gen.video <- param.video (+ optional media.image),
  and gen.video.task_id -> task.watch -> output.preview / output.download.
- When you create a gen.video node, also create a text.negative node with concrete defects
  (blurry, watermark, extra limbs, morphing, flickering, ...) and wire it into the same text input.
  The runner merges negative text into the same content and places it last.
- handle names MUST come from the node type's outputs/inputs in the schema. Do not invent handles.
- every gen.* node needs at least one non-empty text input, wired from a text.prompt or text.negative node.
- image roles first_frame / last_frame are mutually exclusive with reference_image.
- param.video.duration must be an integer: 4-30 for 480p/512p/768P/1080p, 4-15 for 2K.
- never create cycles; a gen.* output task_id may feed task.watch only.
- node ids must be unique and short ascii (e.g. "n_prompt2"). Edge ids are generated by the server; do not set them.
- never leave a node you added unconnected (media.* inputs the user must fill are the only exception).
- Keep the op count small ONLY for pure parameter tweaks (duration / resolution / ratio).
  When the instruction describes a scene or a shot, build the whole runnable chain above.
- If the instruction is already satisfied, return {"reply":"...","ops":[]}.`;

/** 扫描到 end 位置时还开着的括号栈（字符串内的括号不算） */
function stackAt(s, end) {
  const stack = [];
  let inStr = false;
  let esc = false;
  for (let i = 0; i < end && i < s.length; i += 1) {
    const ch = s[i];
    if (esc) { esc = false; continue; }
    if (inStr) {
      if (ch === '\\') esc = true;
      else if (ch === '"') inStr = false;
      continue;
    }
    if (ch === '"') { inStr = true; continue; }
    if (ch === '{' || ch === '[') stack.push(ch);
    else if (ch === '}' || ch === ']') stack.pop();
  }
  return { stack, inStr };
}

/**
 * 括号配平修复：模型经常把 JSON 的多层嵌套括号配错（实测约 20%），
 * finish_reason 还是 stop、字数也完整，所以不能靠重试来解决。
 * 做法是「按 JSON.parse 的报错位置迭代修」：
 *   - 报错处是个多余的闭合符 → 删掉；
 *   - 报错处本该闭合（栈顶还开着对象/数组）→ 插入对应闭合符；
 *   - 报错是「意外结束」→ 把栈里剩下的全补上。
 * 关键保证：修完必须能 JSON.parse 通过，否则返回 null，绝不返回半成品。
 * 纯函数，导出是为了能用真实失败样本做回归测试。
 */
export function repairJson(input) {
  let cur = String(input || '');
  for (let round = 0; round < 40; round += 1) {
    try {
      JSON.parse(cur);
      return cur;
    } catch (err) {
      const msg = String(err.message);
      const pos = Number((/position (\d+)/.exec(msg) || [])[1]);
      // 报错是「内容不完整」：把仍开着的括号补齐
      if (!Number.isFinite(pos)) {
        const { stack } = stackAt(cur, cur.length);
        if (!stack.length) return null;
        for (let i = stack.length - 1; i >= 0; i -= 1) cur += stack[i] === '{' ? '}' : ']';
        continue;
      }
      const { stack, inStr } = stackAt(cur, pos);
      if (inStr) return null;              // 字符串没闭合：补什么都可能改坏原文，不救
      const top = stack[stack.length - 1];
      const ch = cur[pos];
      // 多余的闭合符：删
      if ((ch === '}' && top === '[') || (ch === ']' && top === '{')) {
        cur = cur.slice(0, pos) + cur.slice(pos + 1);
        continue;
      }
      // 该闭合没闭合：插。必须塞在**上一个分隔符之前** —— `}}` 后紧跟 `,` 时，
      // 少的是 op 对象的 `}`，插在 `,` 后面会变成 `,}{` 越插越乱（实测会死循环）
      if (top === '{' || top === '[') {
        let at = pos;
        while (at > 0 && /\s/.test(cur[at - 1])) at -= 1;
        if (cur[at - 1] === ',') at -= 1;
        cur = `${cur.slice(0, at)}${top === '{' ? '}' : ']'}${cur.slice(at)}`;
        continue;
      }
      return null;                          // 栈已空还有多余字符：不是括号问题，不瞎修
    }
  }
  return null;
}

export function createLlm({ getConfig, HttpError }) {
  /** 单次请求：拿到原始响应 → 解析 JSON（含括号修复兜底） */
  async function callOnce({ system, user }) {
    const cfg = await getConfig();
    const llm = cfg.llm || {};
    const base = String(llm.baseUrl || 'https://api.deepseek.com').replace(/\/+$/, '');
    const key = llm.apiKey || process.env.LLM_API_KEY || '';
    const model = llm.model || 'deepseek-flash';
    // 最大输出：设置里可改，非法值一律回落 64K（不传的话 API 侧默认很小，会截断 JSON）
    const maxTokens = Math.max(256, Number(llm.maxTokens) || 65536);
    if (!key) throw new HttpError(400, '未配置 LLM key：请在 config.json 的 llm.apiKey 或环境变量 LLM_API_KEY 里设置');

    let res;
    try {
      res = await fetch(`${base}/chat/completions`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${key}` },
        body: JSON.stringify({
          model,
          temperature: 0,
          // 必须显式给足：不传时 API 侧默认值很小，长图（十几个 ops + 整段英文剧本）
          // 会在这里被截断，JSON 半截直接解析失败，表现为「LLM 输出不是合法 JSON」。
          // 可在设置里改（config.json 的 llm.maxTokens），默认 64K
          max_tokens: maxTokens,
          messages: [
            { role: 'system', content: system },
            { role: 'user', content: user },
          ],
          response_format: { type: 'json_object' },
        }),
      });
    } catch (err) {
      throw new HttpError(502, `连不上 LLM 端点 ${base}：${err.message}`);
    }

    const raw = await res.text();
    let data;
    try { data = JSON.parse(raw); } catch { throw new HttpError(502, `LLM 返回非 JSON：${raw.slice(0, 200)}`); }
    if (!res.ok) throw new HttpError(502, `LLM 错误 ${res.status}：${data?.error?.message || raw.slice(0, 200)}`);

    const choice = data.choices?.[0] || {};
    const text = choice.message?.content || '';
    // usage 一带回上层，用来算上下文占用、做超限告警。
    // 顺带把配置里的 contextWindow 塞进去，前端不用再单独拉一次设置
    const contextWindow = Math.max(1024, Number(llm.contextWindow) || 1048576);
    const usage = data.usage ? { ...data.usage, contextWindow } : null;
    try {
      return { value: JSON.parse(text), usage };
    } catch (err) {
      // ① 先试括号配平修复。注意 repairJson 失败时返回 null，而 JSON.parse(null) 会得到 null
      // 而不抛错，所以这里必须自己判空，不能直接 `return JSON.parse(repairJson(text))`
      const fixed = repairJson(text);
      if (fixed) {
        try {
          const obj = JSON.parse(fixed);
          if (obj && typeof obj === 'object') return { value: obj, usage };
        } catch { /* 修完还是坏的，往下走诊断 */ }
      }
      // ② JSON.parse 的报错带 position，据此把坏点前后截出来 —— 光看开头永远找不到病因
      const pos = Number((/position (\d+)/.exec(String(err.message)) || [])[1]);
      const around = Number.isFinite(pos)
        ? String(text).slice(Math.max(0, pos - 70), pos + 70).replace(/\n/g, '⏎')
        : String(text).slice(0, 260);
      const why = `finish_reason=${choice.finish_reason ?? '-'} completion_tokens=${data.usage?.completion_tokens ?? '-'} chars=${String(text).length} pos=${pos ?? '-'}`;
      throw new HttpError(502, `LLM 输出不是合法 JSON（${why}）：${around}`);
    }
  }

  /**
   * 对外入口：解析失败自动重试一次。
   * 这种「结构残缺」是模型的概率性输出问题，同参数再来一次大概率就正常；
   * 网络/鉴权类错误不重试（重试不会有不同结果，只是白等）。
   */
  async function chatJSON({ system, user }) {
    let lastErr;
    for (let attempt = 0; attempt < 2; attempt += 1) {
      try {
        const out = await callOnce({ system, user });
        return { ...out, attempts: attempt + 1 };
      } catch (err) {
        lastErr = err;
        if (!/不是合法 JSON/.test(String(err.message))) throw err;
      }
    }
    throw lastErr;
  }

  /** 当前图压到最小可读形式，省 token */
  function slimGraph(graph) {
    return {
      nodes: (graph.nodes || []).map((n) => ({ id: n.id, type: n.type, data: n.data })),
      edges: (graph.edges || []).map((e) => ({
        id: e.id, from: `${e.source}.${e.sourceHandle ?? ''}`, to: `${e.target}.${e.targetHandle ?? ''}`,
      })),
    };
  }

  async function planEdit({ graph, instruction, schema }) {
    // schema 可能是 { nodes, rules }（新版）或纯数组（旧调用方），两种都认
    const nodes = Array.isArray(schema) ? schema : schema?.nodes || [];
    const rules = Array.isArray(schema) ? null : schema?.rules || null;
    const user = [
      'Node type schema (inputs/outputs handles, fields, defaults):',
      JSON.stringify(nodes),
      ...(rules ? ['Runnable-graph rules (hard requirements, the graph is rejected without them):', JSON.stringify(rules)] : []),
      '',
      'Current graph:',
      JSON.stringify(slimGraph(graph)),
      '',
      `Instruction: ${instruction}`,
    ].join('\n');

    const { value: out, usage, attempts } = await chatJSON({ system: SYSTEM, user });
    return {
      reply: String(out.reply || ''),
      ops: Array.isArray(out.ops) ? out.ops : [],
      usage,
      attempts,
    };
  }

  /* ── 提示词优化：只回文本，不碰图 ── */

  const OPTIMIZE_SYSTEM = `You are a prompt engineer for a text-to-video model (MiniMax-H3).
Rewrite the user's prompt into a tighter, more shootable one. Answer with strict json only (json_object mode), e.g.:
{"text": "<the rewritten prompt>", "note": "<one short sentence in Simplified Chinese on what you changed>"}

Rules:
- Keep the user's original language. Keep every concrete intent (character, setting, action, style). Do not invent new subjects.
- For kind=prompt: one continuous clear description. Put pacing up front when motion matters (e.g. "real-time pacing, no slow motion"). Use beats for multi-step action. Add a CONSISTENCY clause when a character must stay identical. Never ask for readable on-screen text: dense text renders as garbage, so describe it as soft blurred light streaks instead.
- For kind=negative: output a comma-separated list of defects to avoid (no readable text, no watermark, no extra limbs, no morphing, ...). No sentences, no "Negative:" prefix, no duplicates.
- Never add markdown, quotes or explanations inside "text".
- If the input is already good, return it nearly unchanged and say so in note.`;

  async function optimizePrompt({ text, kind = 'prompt', context = '' }) {
    const body = String(text || '').trim();
    if (!body) throw new HttpError(400, '提示词为空');
    if (body.length > 6000) throw new HttpError(400, '提示词太长（上限 6000 字符），先拆成多个节点');
    const user = [
      `kind: ${kind === 'negative' ? 'negative' : 'prompt'}`,
      context ? `context: ${context}` : '',
      'prompt:',
      body,
    ].filter(Boolean).join('\n');
    const { value: out } = await chatJSON({ system: OPTIMIZE_SYSTEM, user });
    const optimized = String(out.text || '').trim();
    if (!optimized) throw new HttpError(502, '模型没有返回优化结果，请重试');
    return { text: optimized, note: String(out.note || ''), original: body };
  }

  return { chatJSON, planEdit, optimizePrompt };
}
